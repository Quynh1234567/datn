"""Xuất mô hình đã lượng tử hóa thành các file nạp cho FPGA và ESP32-S3.

Thư mục outputs/fpga/:
  mem/sv.mem                 N_SV·DIM dòng, mỗi dòng 1 phần tử DATA_W bit (SV0[0], SV0[1], …)
  mem/sv_packed.mem          N_SV dòng, mỗi dòng = DIM phần tử ghép (phần tử 0 ở LSB)
  mem/alpha.mem              N_SV dòng, hệ số α (COEF_W bit, có dấu)
  mem/exp_lut.mem            LUT_SIZE dòng, exp(−t) không dấu Q0.LUT_W
  mem/scaler_mean.mem        DIM dòng, trung bình chuẩn hóa (Q·DATA_FRAC, 32 bit)  – tùy chọn
  mem/scaler_inv_std.mem     DIM dòng, 1/σ (Q·16, 32 bit không dấu)                 – tùy chọn
  mem/test_input.mem         N_TEST·DIM dòng, véc-tơ đầu vào đã lượng tử hóa
  mem/test_expected_score.mem N_TEST dòng, f_q (ACC_W bit, có dấu)
  mem/test_expected_label.mem N_TEST dòng, 1 = bất thường
  mem/test_kernel_vec0.mem   N_SV dòng, k_q của véc-tơ test đầu tiên (gỡ lỗi PE)
  coe/*.coe                  cùng nội dung cho Vivado Block Memory Generator
  ocsvm_params.vh            localparam cho RTL
  ocsvm_params.h             header C cho ESP32-S3 (tiền xử lý, chuẩn hóa, giao thức UART)
  model_float.json           mô hình số thực đầy đủ (tham chiếu)
"""
from __future__ import annotations

import math
from datetime import datetime
from pathlib import Path

import numpy as np

from ..features.covariance import FEATURE_SETS
from ..quantization.fixed_point import to_fixed, to_hex
from ..quantization.golden_model import FixedPointOCSVM
from ..utils import save_json


def write_mem(path: Path, values, width: int, header: str | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    if header:
        lines += [f"// {h}" for h in header.splitlines()]
    lines += to_hex(values, width)
    path.write_text("\n".join(lines) + "\n")


def write_packed_mem(path: Path, matrix: np.ndarray, width: int, header: str | None = None) -> None:
    """Mỗi hàng của matrix ghép thành 1 từ rộng; phần tử cột 0 nằm ở các bit thấp nhất."""
    mask = (1 << width) - 1
    total = width * matrix.shape[1]
    nd = math.ceil(total / 4)
    lines = [f"// {h}" for h in (header or "").splitlines() if header]
    for row in matrix:
        word = 0
        for j, v in enumerate(row):
            word |= (int(v) & mask) << (j * width)
        lines.append(format(word, f"0{nd}X"))
    path.write_text("\n".join(lines) + "\n")


def write_coe(path: Path, values, width: int) -> None:
    """File .coe (radix 16) cho Xilinx Block Memory Generator."""
    path.parent.mkdir(parents=True, exist_ok=True)
    hx = to_hex(values, width)
    body = ",\n".join(hx) + ";"
    path.write_text("memory_initialization_radix=16;\nmemory_initialization_vector=\n" + body + "\n")


def _vlit(v: int, width: int) -> str:
    """Hằng số Verilog có dấu: 48'sd123 hoặc -48'sd123."""
    return f"{width}'sd{v}" if v >= 0 else f"-{width}'sd{-v}"


def _c_array(name: str, values, ctype: str = "float", per_line: int = 6) -> str:
    vals = [f"{v:.9e}f" if ctype == "float" else str(int(v)) for v in np.ravel(values)]
    rows = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def write_c_model_data(fx: FixedPointOCSVM, path: Path, stamp: str) -> None:
    """Mảng SV/α/LUT dạng C – để chạy cùng datapath số nguyên trên CPU ESP32
    (baseline phần mềm khi đo tốc độ tăng tốc của FPGA, và để kiểm tra chéo)."""
    p = fx.p
    n_sv, dim = fx.sv_q.shape
    txt = f"""/* ocsvm_model_data.h - auto-generated by ocsvm_fpga ({stamp})
 * Cung du lieu voi sv.mem / alpha.mem / exp_lut.mem. Chi #include trong MOT file .c */
#ifndef OCSVM_MODEL_DATA_H
#define OCSVM_MODEL_DATA_H
#include <stdint.h>
#define OCSVM_N_SV       {n_sv}
#define OCSVM_GAMMA_Q    {fx.gamma_q}LL
#define OCSVM_LUT_SHIFT  {p.lut_shift}
#define OCSVM_LUT_SIZE   {p.lut_size}
#define OCSVM_RHO_Q      ({fx.rho_q}LL)
"""
    txt += _c_array("OCSVM_SV_Q", fx.sv_q, "int16_t", 12)
    txt += _c_array("OCSVM_ALPHA_Q", fx.coef_q, "int16_t", 12)
    lut_t = "uint16_t" if p.lut_width <= 16 else "uint32_t"   # LUT 20 bit không vừa uint16
    txt += _c_array("OCSVM_EXP_LUT", fx.exp_lut, lut_t, 12)
    txt += "#endif /* OCSVM_MODEL_DATA_H */\n"
    path.write_text(txt, encoding="ascii")


def export_all(fx: FixedPointOCSVM, cfg, out_dir: Path, test_x_raw: np.ndarray | None,
               test_y: np.ndarray | None, rng: np.random.Generator, logger=None, quantize_fn=None) -> dict:
    """quantize_fn(x_raw) → (x_q, số phần tử bão hòa): cách lượng tử véc-tơ kiểm thử. Mặc định
    fx.quantize_input (chuẩn hóa số thực); grid_flow_hw truyền đường z số nguyên giống FPGA."""
    p = fx.p
    det = fx.det
    n_sv, dim = fx.sv_q.shape
    mem, coe = out_dir / "mem", out_dir / "coe"
    mem.mkdir(parents=True, exist_ok=True)

    # ---------------------------------------------------------------- tham số mô hình
    write_mem(mem / "sv.mem", fx.sv_q, p.data_width)
    write_packed_mem(mem / "sv_packed.mem", fx.sv_q, p.data_width)
    write_mem(mem / "alpha.mem", fx.coef_q, p.coef_width)
    write_mem(mem / "exp_lut.mem", fx.exp_lut, p.lut_width)
    write_coe(coe / "sv.coe", fx.sv_q, p.data_width)
    write_coe(coe / "alpha.coe", fx.coef_q, p.coef_width)
    write_coe(coe / "exp_lut.coe", fx.exp_lut, p.lut_width)

    mean_q = to_fixed(det.scaler.mean, 32, p.data_frac, True)
    inv_std_q = to_fixed(1.0 / det.scaler.scale, 32, 16, False)
    write_mem(mem / "scaler_mean.mem", mean_q, 32)
    write_mem(mem / "scaler_inv_std.mem", inv_std_q, 32)

    # ---------------------------------------------------------------- vector kiểm thử
    n_test = 0
    if test_x_raw is not None and len(test_x_raw):
        k = min(int(cfg.fpga.num_test_vectors), len(test_x_raw))
        if test_y is not None and len(np.unique(test_y)) == 2:      # cân bằng hai lớp
            ab, no = np.flatnonzero(test_y == 1), np.flatnonzero(test_y == 0)
            sel = np.concatenate([rng.choice(ab, min(k // 2, len(ab)), replace=False),
                                  rng.choice(no, min(k - min(k // 2, len(ab)), len(no)), replace=False)])
        else:
            sel = rng.choice(len(test_x_raw), k, replace=False)
        sel = np.sort(sel)
        xq, _ = (quantize_fn or fx.quantize_input)(test_x_raw[sel])
        fq = fx.decision_q(xq)
        write_mem(mem / "test_input.mem", xq, p.data_width)
        write_packed_mem(mem / "test_input_packed.mem", xq, p.data_width)
        write_mem(mem / "test_expected_score.mem", fq, p.acc_width)
        write_mem(mem / "test_expected_label.mem", fx.anomaly_q(fq), 1)
        write_mem(mem / "test_kernel_vec0.mem", fx.kernel_q(xq[:1])[0], p.lut_width + 1)
        if test_y is not None:
            write_mem(mem / "test_ground_truth.mem", test_y[sel], 1)
        n_test = len(sel)

    # ---------------------------------------------------------------- Verilog header
    w = fx.internal_widths(dim)
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    vh = f"""// ============================================================================
// ocsvm_params.vh - auto-generated by ocsvm_fpga ({stamp})
// Model: {det.meta.get('model_type', '?')} | feature set {cfg.features.feature_set} | gamma = {det.model.gamma:.6g}
// f(x) = sum_i ALPHA[i] * EXP_LUT[ (sum_j (x_j - SV[i][j])^2 * GAMMA_Q) >> LUT_SHIFT ] - RHO_Q
// File ASCII-only de tuong thich moi cong cu (Vivado, Quartus, ModelSim, Icarus).
// ============================================================================
`ifndef OCSVM_PARAMS_VH
`define OCSVM_PARAMS_VH

localparam integer N_SV        = {n_sv};      // so Support Vector
localparam integer DIM         = {dim};      // so chieu vector dac trung
localparam integer DATA_W      = {p.data_width};      // x, sv : Q{p.data_width - p.data_frac - 1}.{p.data_frac} co dau
localparam integer DATA_FRAC   = {p.data_frac};
localparam integer COEF_W      = {p.coef_width};      // alpha : Q{p.coef_width - p.coef_frac - 1}.{p.coef_frac} co dau
localparam integer COEF_FRAC   = {p.coef_frac};
localparam integer GAMMA_W     = {p.gamma_width};      // gamma khong dau
localparam integer GAMMA_FRAC  = {p.gamma_frac};
localparam integer GAMMA_Q     = {fx.gamma_q};
localparam integer LUT_ADDR_W  = {p.lut_addr_bits};
localparam integer LUT_SIZE    = {p.lut_size};
localparam integer LUT_W       = {p.lut_width};      // exp(-t) : Q0.{p.lut_width} khong dau
localparam integer LUT_SHIFT   = {p.lut_shift};      // dia chi LUT = t_full >> LUT_SHIFT
localparam integer ACC_W       = {p.acc_width};
localparam integer ACC_FRAC    = {p.acc_frac};
localparam integer DIFF_W      = {w['DIFF_W']};      // x - sv
localparam integer DIST_W      = {w['DIST_W']};      // sum (x - sv)^2
localparam integer T_W         = {w['T_W']};      // dist * GAMMA_Q
localparam integer PROD_W      = {w['PROD_W']};      // alpha * k
localparam signed [ACC_W-1:0] RHO_Q = {_vlit(fx.rho_q, p.acc_width)};
localparam signed [ACC_W-1:0] THR_Q = {_vlit(fx.thr_q, p.acc_width)};
localparam integer DECISION_MODE = {p.mode};  // 0: anomaly = (f < THR) [OC-SVM] | 1: anomaly = (|f| > THR) [LS-OC-SVM]
localparam integer N_TEST      = {n_test};      // so vector trong test_input.mem
localparam integer SMOOTH_WIN  = {det.smoothing};      // trung binh truot f(x) sau FPGA

`endif
"""
    (out_dir / "ocsvm_params.vh").write_text(vh, encoding="ascii")

    # ---------------------------------------------------------------- C header ESP32
    pp, of, ft = cfg.preprocess, cfg.optical_flow, cfg.features
    names = FEATURE_SETS[ft.feature_set]

    _g = ft.get("descriptor", "covariance") in ("grid_flow", "grid_flow_hw")
    if _g:
        from ..features.grid_flow import grid_layout
        _yv, _xv = grid_layout(ft, int(pp.height), int(pp.width))
        _ye = ", ".join(str(int(v)) for v in _yv)
        _xe = ", ".join(str(int(v)) for v in _xv)
        grid_block = (f"#define GRID_ROWS            {len(_yv) - 1}\n"
                      f"#define GRID_COLS            {len(_xv) - 1}\n"
                      f"#define GRID_NSTATS          {dict(basic=3, max=4, rich=5)[ft.get('grid_stats', 'basic')]}   /* 3: [u,v,|v|]  4: + max|v|  5: + max|v|, std|v| */\n"
                      f"#define GRID_DIFF            {int(bool(ft.get('grid_diff', False)))}   /* 1: them mean|I2-I1| moi o */\n"
                      f"#define GRID_Y_EDGES         {{ {_ye} }}\n"
                      f"#define GRID_X_EDGES         {{ {_xe} }}\n"
                      f"#define GRID_LOG_SCALE       {float(ft.get('grid_log_scale', 0) or 0)!r}f   /* >0: nen bien do */")
    else:
        grid_block = "/* (khong dung dac trung luoi) */"
    hdr = f"""/* ============================================================================
 * ocsvm_params.h - auto-generated by ocsvm_fpga ({stamp})
 * ESP32-S3: tien xu ly -> Horn-Schunck -> ma tran hiep bien -> logm
 *           -> chuan hoa -> luong tu Q{p.data_width - p.data_frac - 1}.{p.data_frac} -> UART -> FPGA.
 * MOI tham so duoi day phai giu nguyen nhu luc huan luyen.
 * ==========================================================================*/
#ifndef OCSVM_PARAMS_H
#define OCSVM_PARAMS_H
#include <stdint.h>

/* --- Tien xu ly (OV5640: PIXFORMAT_GRAYSCALE, FRAMESIZE_QQVGA) --- */
#define FRAME_W              {pp.width}
#define FRAME_H              {pp.height}
#define FRAME_STEP           {pp.frame_step}      /* khoang cach = FRAME_STEP khung cua video huan luyen (IITB 25 fps) */
#define SKIP_DARK_BELOW      {float(pp.get('skip_dark_below', 0) or 0)!r}f
#define ASPECT_CROP          {int(pp.aspect_mode == 'crop')}
#define GAUSS_KSIZE          {pp.gaussian_ksize}
#define GAUSS_SIGMA          {float(pp.gaussian_sigma)!r}f

/* --- Horn-Schunck --- */
#define HS_ALPHA             {float(of.alpha)!r}f
#define HS_NUM_ITER          {of.num_iter}
#define HS_INTENSITY_SCALE   {float(of.intensity_scale)!r}f

/* --- Dac trung diem anh: {ft.feature_set} = [{', '.join(names)}] --- */
#define OCSVM_DESCRIPTOR     {0 if ft.get('descriptor', 'covariance') == 'covariance' else 1}   /* 0 = hiep bien F1..F4, 1 = luoi o thong ke dong quang hoc */
{grid_block}
#define FEATURE_SET_ID       {int(ft.feature_set[1:])}   /* 1..4 = F1..F4 */
#define FEAT_D               {len(names)}
#define PIXEL_STRIDE         {ft.pixel_stride}
#define PIXEL_BORDER         {ft.border}
#define NORMALIZE_COORDS     {int(ft.normalize_coords)}
#define MOTION_THRESHOLD     {float(ft.motion_threshold)!r}f
#define MIN_MOTION_PIXELS    {ft.min_motion_pixels}
#define COV_EPSILON          {float(ft.cov_epsilon)!r}f
#define LOG_EUCLIDEAN        {int(ft.log_euclidean)}   /* vec = vech(logm(C)), phan tu ngoai cheo x sqrt(2) */

/* --- Vector gui sang FPGA --- */
#define OCSVM_DIM            {dim}
#define OCSVM_DATA_W         {p.data_width}
#define OCSVM_DATA_FRAC      {p.data_frac}
#define OCSVM_ACC_W          {p.acc_width}
#define OCSVM_ACC_FRAC       {p.acc_frac}
#define OCSVM_COEF_SCALE     ({p.coef_scale:.9e})   /* f_float = f_q / 2^ACC_FRAC / COEF_SCALE */
#define OCSVM_SMOOTH_WIN     {det.smoothing}
#define OCSVM_DECISION_MODE  {p.mode}
#define OCSVM_THR_Q          ({fx.thr_q}LL)
#define OCSVM_THR_FLOAT      ({det.model.decision_threshold_from_score(det.threshold):.9e})
/* Canh bao co tre (hysteresis) tren mien diem so: score = -f (mode 0) hoac |f| (mode 1)
 * BAT khi score > ON; TAT khi score < OFF lien tuc qua HOLD cap khung. */
#define OCSVM_ALARM_ON_SCORE  ({float(det.threshold):.9e})
#define OCSVM_ALARM_OFF_SCORE ({float((det.meta.get('alarm') or {}).get('off', det.threshold)):.9e})
#define OCSVM_ALARM_HOLD      {int((det.meta.get('alarm') or {}).get('hold', 0))}

/* --- Giao thuc UART de xuat (little-endian) ---
 * ESP32 -> FPGA : 0xAA 0x55 | DIM x int16 | XOR checksum (1 byte)
 * FPGA -> ESP32 : 0x5A      | f_q ({p.acc_width} bit = {p.acc_width // 8} byte) | flag (1 byte) | XOR checksum */
#define UART_SYNC0           0xAA
#define UART_SYNC1           0x55
#define UART_RESP_SYNC       0x5A

/* z = (x - mean) * inv_std ;  x_q = sat(round(z * 2^DATA_FRAC)) */
{_c_array('OCSVM_SCALER_MEAN', det.scaler.mean)}
{_c_array('OCSVM_SCALER_INV_STD', 1.0 / det.scaler.scale)}
#endif /* OCSVM_PARAMS_H */
"""
    (out_dir / "ocsvm_params.h").write_text(hdr, encoding="ascii")

    # ---------------------------------------------------------------- dữ liệu mô hình cho C
    write_c_model_data(fx, out_dir / "ocsvm_model_data.h", stamp)

    # ---------------------------------------------------------------- mô hình số thực
    km = det.model
    save_json({
        "model_type": det.meta.get("model_type"), "feature_set": ft.feature_set,
        "gamma": km.gamma, "rho": km.rho, "mode": km.mode,
        "threshold_score": det.threshold, "smoothing": det.smoothing,
        "coefs": km.coefs, "support_vectors": km.support_vectors,
        "scaler_mean": det.scaler.mean, "scaler_scale": det.scaler.scale,
        "quant": fx.summary(),
    }, out_dir / "model_float.json")
    if logger:
        logger.info(f"Đã xuất {n_sv} SV × {dim} chiều, {n_test} vector kiểm thử → {out_dir}")
    return {"n_sv": n_sv, "dim": dim, "n_test_vectors": n_test}
